#include "esp_log.h"
#include "board_profile.h"
#include "brand_profile.h"
#include "nvs_config.h"
#include "lcd_driver.h"
#include "lvgl_port.h"
#include "ui_screens.h"
#include "assets_brand.h"
#include "wifi_manager.h"
#include "mqtt_bridge.h"
#include "ota_manager.h"
#include "sdkconfig.h"

#if CONFIG_SPARKPLUG_B_ENABLED
#include "espnow_manager.h"
#include "sparkplug_b.h"
#endif

static const char *TAG = "gateway";

#if CONFIG_SPARKPLUG_B_ENABLED
/* The Sparkplug module never talks to the radio: it translates a command
 * into an ESP-NOW frame and hands it to this sink, which forwards it to the
 * ESP-NOW manager. */
static esp_err_t espnow_sink(const uint8_t *frame, size_t len, void *ctx)
{
    (void)ctx;
    return espnow_manager_send(frame, len);
}
#endif

void app_main(void)
{
    const esp_err_t nvs_err = nvs_config_init();
    if (nvs_err != ESP_OK) {
        ESP_LOGE(TAG, "NVS initialization failed: %s", esp_err_to_name(nvs_err));
        return;
    }

    board_profile_t profile;
    const esp_err_t err = board_profile_read(&profile);

    if (err != ESP_OK) {
        ESP_LOGE(TAG, "Board profile read failed: %s", esp_err_to_name(err));
        return;
    }

    ESP_LOGI(TAG, "ESP32-S3 profile: flash=%lu bytes, PSRAM=%u bytes",
             (unsigned long)profile.flash_size_bytes,
             (unsigned int)profile.psram_size_bytes);

    /* Issue #12: the brand identity of this build.
     *
     * The profile is selected at build time (Kconfig choice + versioned
     * assets), so the name, the model, the version, the revision and the
     * OTA channel reported here are the ones this image was built with.
     * The same values reach the LCD through the boot splash and the API
     * through the brand payload. */
    const esp_err_t brand_err = brand_profile_log();
    if (brand_err != ESP_OK) {
        ESP_LOGE(TAG, "Brand profile is invalid: %s", esp_err_to_name(brand_err));
        return;
    }

    /* Issue #10 init chain (contracts only — display chain stays on hold).
     *
     * The four calls below initialize the LVGL display chain components
     * shipped in PRs #29 (display_manager, already invoked elsewhere on
     * the carrier init path; not invoked here), #31 (lcd_driver), #32
     * (lvgl_port), #33 (ui_screens), and #34 (assets_brand).
     *
     * The order mirrors the dependency chain documented in
     * odd/tasks/issue-10-st7789-lvgl.md:
     *
     *     display_manager  (carrier init — not touched here)
     *         |
     *         +-- lcd_driver  (panel contact map + GPIO22 candidate)
     *              |
     *              +-- lvgl_port  (LVGL adapter, contract only)
     *                   |
     *                   +-- ui_screens  (six screen stubs)
     *
     * assets_brand is a standalone component (no display chain
     * dependency), so its init is independent of the chain ordering.
     *
     * Every call is a contract-only stub in this slice: each function
     * logs a single line via ESP_LOGI and returns ESP_OK. The display
     * bring-up is gated on physical carrier verification. */
    const esp_err_t lcd_err = lcd_driver_init();
    if (lcd_err != ESP_OK) {
        ESP_LOGE(TAG, "LCD driver init failed: %s", esp_err_to_name(lcd_err));
        return;
    }

    const esp_err_t lvgl_err = lvgl_port_init();
    if (lvgl_err != ESP_OK) {
        ESP_LOGE(TAG, "LVGL port init failed: %s", esp_err_to_name(lvgl_err));
        return;
    }

    const esp_err_t ui_err = ui_screens_init();
    if (ui_err != ESP_OK) {
        ESP_LOGE(TAG, "UI screens init failed: %s", esp_err_to_name(ui_err));
        return;
    }

    /* Issue #12: the boot splash is the first thing the product shows, so it
     * carries the identity of the brand profile. The LVGL rendering lands
     * with the display bring-up; for now the screen publishes the line the
     * local display will show, which is the same one the API serves. */
    ui_boot_screen();

    const esp_err_t assets_err = assets_brand_init();
    if (assets_err != ESP_OK) {
        ESP_LOGE(TAG, "Assets brand init failed: %s", esp_err_to_name(assets_err));
        return;
    }

    /* Issue #21 (Phase 0, T0.6.1-T0.6.2): bring up the Wi-Fi driver in
     * AP+STA mode. Credentials are loaded by wifi_manager_init from
     * the gitignored `wifi_credentials.local.h`, generated by
     * `tools/gen-wifi-credentials.sh` from `/.env` at the repo root.
     * STA association is skipped when the local header is absent or
     * empty (CI mode); the AP always comes up with Kconfig defaults.
     *
     * The init/deinit pair is not idempotent. The gateway stays
     * running after this point so the SPA/REST/WebSocket layer can
     * attach on the same AP/STA network.
     *
     * Issue #12: the soft-AP advertises the SSID of the brand profile.
     * Only the SSID is public configuration; the AP password stays a
     * manufacturing secret injected through the gitignored local header,
     * so the AP falls back to open mode when no secret was injected. */
    wifi_manager_credentials_t brand_wifi = {0};
    brand_wifi.ap_ssid = brand_profile_get()->ap_ssid;

    wifi_manager_credentials_t wifi_credentials = {0};
    const esp_err_t creds_err = wifi_manager_apply_credentials(&brand_wifi,
                                                              &wifi_credentials);
    if (creds_err != ESP_OK) {
        ESP_LOGE(TAG, "Wi-Fi credentials failed to resolve: %s",
                 esp_err_to_name(creds_err));
        return;
    }

    const esp_err_t wifi_err = wifi_manager_init(&wifi_credentials);
    if (wifi_err != ESP_OK) {
        ESP_LOGE(TAG, "Wi-Fi manager init failed: %s", esp_err_to_name(wifi_err));
        return;
    }

    const esp_err_t mqtt_err = mqtt_bridge_start();
    if (mqtt_err != ESP_OK) {
        ESP_LOGE(TAG, "MQTT bridge start failed: %s", esp_err_to_name(mqtt_err));
        return;
    }

    /* Issue #13: the OTA manager.
     *
     * The manager is initialised after NVS, because the URL of the release
     * server is provisioned there, and before the subsystems are up, so a
     * watchdog is already watching the confirmation window when the image
     * happens to be on trial.
     *
     * When the running image was installed by an update and has not
     * confirmed itself yet, it is on trial: the bootloader rolls it back if
     * the unit reboots before the confirmation. The confirmation only
     * happens once the subsystems above are alive, because an image that
     * cannot reach the network is not a working image. */
    const esp_err_t ota_err = ota_manager_init();
    if (ota_err != ESP_OK) {
        ESP_LOGE(TAG, "OTA manager init failed: %s", esp_err_to_name(ota_err));
        return;
    }

    if (ota_manager_image_pending()) {
        const esp_err_t confirm_err = ota_manager_confirm_pending_image();
        if (confirm_err != ESP_OK) {
            ESP_LOGE(TAG, "The new image could not be confirmed: %s",
                     esp_err_to_name(confirm_err));
            return;
        }
    }

#if CONFIG_SPARKPLUG_B_ENABLED
    /* Register the ESP-NOW sink before the first command can arrive, so a
     * DCMD that asks a node to reboot or to change its sleep interval has
     * somewhere to go. */
    const esp_err_t sink_err = sparkplug_b_set_espnow_sink(espnow_sink, NULL);
    if (sink_err != ESP_OK) {
        ESP_LOGE(TAG, "ESP-NOW sink registration failed: %s", esp_err_to_name(sink_err));
        return;
    }
#endif
}
