#!/usr/bin/env bash
#
# tools/brand/gen-brand-secrets.sh
#
# Reads the gitignored `/.env` at the repo root and emits
# `firmware/gateway/components/brand_profile/include/brand_secrets.local.h`
# (also gitignored) with the manufacturing secrets the gateway expects.
#
# This is the *secret* half of the white-label layer. The *public* half — the
# brand name, the model, the colours, the support URL, the initial SSID — is
# authored in the brand Kconfig and lives in Git. Keeping the two apart is
# what allows the public configuration to be reviewed and released while the
# per-unit secrets stay on the manufacturing machine.
#
# Behavior:
# - If `.env` is missing OR all keys are empty: emit a sentinel file that
#   defines no secret and documents the fallback. The build still succeeds
#   and the gateway reports "manufacturing secrets absent".
# - Otherwise emit the macros that are present. A key that is absent is
#   simply not defined, so the firmware sees NULL for that field.
#
# Usage:
#     bash tools/brand/gen-brand-secrets.sh            # write the file
#     bash tools/brand/gen-brand-secrets.sh --dry-run  # print what would be written
#
# Never echo an actual secret. The --dry-run mode prints `(set)` or
# `(empty)` for each key, never the literal value.
#
# This script must be invoked from the repo root (the directory that contains
# .env and firmware/). The caller can override the repo root with
# BRAND_REPO_ROOT=/path/to/repo.

set -euo pipefail

REPO_ROOT="${BRAND_REPO_ROOT:-$(git rev-parse --show-toplevel 2>/dev/null || pwd)}"
ENV_FILE="${REPO_ROOT}/.env"
OUT_FILE="${REPO_ROOT}/firmware/gateway/components/brand_profile/include/brand_secrets.local.h"
OUT_DIR="$(dirname "${OUT_FILE}")"

DRY_RUN=0
if [[ "${1:-}" == "--dry-run" ]]; then
    DRY_RUN=1
fi

# Read a single key from .env. Returns an empty string if missing.
read_env() {
    local key="$1"
    if [[ ! -f "${ENV_FILE}" ]]; then
        echo ""
        return
    fi
    # Match `KEY=value` (allow optional surrounding whitespace; ignore
    # comment lines that happen to contain `KEY=`).
    local val
    val="$(grep -E "^[[:space:]]*${key}[[:space:]]*=" "${ENV_FILE}" \
            | tail -n1 \
            | sed -E "s/^[[:space:]]*${key}[[:space:]]*=[[:space:]]*//")"
    # Strip optional double quotes around the value.
    val="${val%\"}"
    val="${val#\"}"
    # Strip optional single quotes.
    val="${val%\'}"
    val="${val#\'}"
    echo "${val}"
}

PROVISIONING_KEY="$(read_env BRAND_SECRET_PROVISIONING_KEY)"
SUPPORT_TOKEN="$(read_env BRAND_SECRET_SUPPORT_TOKEN)"
AP_PASSWORD="$(read_env BRAND_SECRET_AP_PASSWORD)"

# In dry-run mode the value of a secret is replaced by a placeholder, so the
# printed file can be pasted into a ticket without leaking anything.
secret_value() {
    if [[ "${DRY_RUN}" -eq 1 ]]; then
        echo "<redacted>"
    else
        echo "$1"
    fi
}

emit_file() {
    cat <<HEADER
/**
 * @file brand_secrets.local.h
 * @brief Manufacturing secrets of the gateway (gitignored).
 *
 * Generated by tools/brand/gen-brand-secrets.sh. Do not edit by hand;
 * the script overwrites this file on every invocation. The source
 * of truth is \`/.env\` at the repo root, also gitignored.
 *
 * Never commit this file. Never paste its contents into an issue,
 * a chat message, or a public log. Keep secrets on disk only.
 *
 * The public identity of the product (name, model, colours, support URL,
 * initial SSID) is NOT here: it is authored in the brand Kconfig and is
 * versioned in Git.
 */
#pragma once

HEADER

    if [[ -z "${PROVISIONING_KEY}" && -z "${SUPPORT_TOKEN}" && -z "${AP_PASSWORD}" ]]; then
        cat <<EMPTY
/* No manufacturing secrets present in .env.
 * The gateway reports "manufacturing secrets absent" and leaves every
 * secret field empty. To provision a unit, set BRAND_SECRET_PROVISIONING_KEY,
 * BRAND_SECRET_SUPPORT_TOKEN or BRAND_SECRET_AP_PASSWORD in .env and re-run
 * tools/brand/gen-brand-secrets.sh. */

#define BRAND_SECRETS_SOURCE_NONE 1
EMPTY
        return
    fi

    cat <<PREAMBLE
/* Manufacturing secrets generated from \`/.env\`. */
/* Provisioning key: $( [[ -n "${PROVISIONING_KEY}" ]] && echo set || echo empty ) */
/* Support token:    $( [[ -n "${SUPPORT_TOKEN}" ]] && echo set || echo empty ) */
/* AP password:      $( [[ -n "${AP_PASSWORD}" ]] && echo set || echo empty ) */

#define BRAND_SECRETS_SOURCE_ENV 1

PREAMBLE

    if [[ -n "${PROVISIONING_KEY}" ]]; then
        printf '#define BRAND_SECRET_PROVISIONING_KEY  "%s"\n' "$(secret_value "${PROVISIONING_KEY}")"
    fi
    if [[ -n "${SUPPORT_TOKEN}" ]]; then
        printf '#define BRAND_SECRET_SUPPORT_TOKEN     "%s"\n' "$(secret_value "${SUPPORT_TOKEN}")"
    fi
    if [[ -n "${AP_PASSWORD}" ]]; then
        printf '#define BRAND_SECRET_AP_PASSWORD       "%s"\n' "$(secret_value "${AP_PASSWORD}")"
    fi
}

if [[ "${DRY_RUN}" -eq 1 ]]; then
    echo "# dry-run: would write ${OUT_FILE}"
    emit_file
    exit 0
fi

mkdir -p "${OUT_DIR}"
emit_file > "${OUT_FILE}"
echo "wrote ${OUT_FILE}"
